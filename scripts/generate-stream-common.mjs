import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'contracts/stream-common/model.json'), 'utf8');
const model = JSON.parse(source);
if (model.scope !== 'model-selector-rejection' || !Array.isArray(model.selectors) ||
    !model.selectors.length || !model.selectors.every(key => typeof key === 'string' && /^[A-Za-z]+$/.test(key)) ||
    new Set(model.selectors).size !== model.selectors.length) throw new Error('Invalid current model selector specification');
const output = resolve(root, 'src/uns-v2/source-stream-model.generated.ts');
const generated = '// Generated by scripts/generate-stream-common.mjs. DO NOT EDIT.\n' +
  `export const CURRENT_MODEL_SELECTORS = ${JSON.stringify(model.selectors)} as const;\n` +
  `export const CURRENT_MODEL_SPEC_SHA256 = ${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Current model generated constants are stale');
} else writeFileSync(output, generated);
